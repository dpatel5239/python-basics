                      # **Typecasting in Python**
age = 25
height = 5.9
full_name = "John Doe"
ans = False

print(float(age))# typecasting int to float
print(int(height))  # typecasting float to int
print(str(full_name))  # typecasting string to string, there is no type casting from string to int/float unless the string is a proper numeric literal
print(str(ans))  # typecasting boolean to string
print(bool(age))  # typecasting int to boolean, any non-zero integer is considered True, and zero is considered False
print(bool(height))  # typecasting float to boolean, any non-zero float is considered True, and zero is considered False
print(bool(full_name))  # typecasting string to boolean, any non-empty string is considered True, and an empty string is considered False



